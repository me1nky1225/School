# 文件说明：DHT11 温湿度传感器单模块测试程序（课程实验例程，用于前期硬件验证）
# 功能简介：每 5 秒读取一次 DHT11 的温度与湿度，同时输出到 Thonny 串口和
#           SSD1306 OLED 屏，用于验证传感器接线与驱动是否正常工作。
#           本文件不参与系统最终运行，主程序 main.py 已内置相同的采集逻辑
#           （并增加了采样间隔限制与失败重试）。
